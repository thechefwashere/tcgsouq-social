-- 0002_shopify_referrer_backfill.sql
--
-- WHAT THIS IS
--   Daily PokeSouq storefront traffic and order performance, broken out by
--   referrer source, for the entire history of the store. One row per
--   (day, referrer_source). Loads into shopify_referrer_daily.
--
-- DATE RANGE   2023-05-01 .. 2026-09-14 (inclusive)
-- ROW COUNT    4766 rows across 1233 days
-- SOURCE       Shopify ShopifyQL via the Shopify Admin analytics API,
--              extracted 2026-09-14. Two query families, merged on (day, source):
--                FROM sessions SHOW sessions GROUP BY referrer_source TIMESERIES day
--                FROM sales SHOW orders, total_sales GROUP BY order_referrer_source TIMESERIES day
--              Each yearly/half-yearly chunk was reconciled against the row count
--              and summary metric Shopify returned for that chunk before merging.
--
-- TRANSFORMATIONS APPLIED (explicit, so the raw data can be reconstructed)
--
--   1. EMPTY STRING -> 'direct' (sales side only).
--      The sales query returns an EMPTY STRING '' for the no-referrer bucket,
--      where the sessions query returns the literal 'direct'. These are the same
--      bucket. Every '' returned by the sales query is rewritten to 'direct'
--      before merging, so each day carries ONE 'direct' row holding both its
--      sessions and its orders.
--
--   2. EMPTY STRING -> 'unattributed' (sessions side only).
--      The sessions query ALSO emits an ''-keyed bucket, but it is NOT the same
--      thing as the sales ''. It is a distinct bucket that co-exists with a
--      separate 'direct' row on the same day (e.g. 2024-03-01 returns '' = 13
--      sessions AND 'direct' = 64 sessions), and it carries the bulk of traffic
--      during 2024-02-22..2024-03-01, when Shopify's referrer attribution was
--      evidently not resolving. It is preserved here under the name
--      'unattributed' rather than being folded into 'direct', which would have
--      overstated direct traffic for that window. Outside that window it appears
--      only on days with zero total sessions, carrying the value 0.
--
--   3. NOTHING ELSE. No interpolation, no gap-filling, no rounding.
--
-- NULL vs ZERO
--   Where a (day, source) pair appears in one dataset but not the other, the
--   missing columns are written as NULL - never as 0. NULL means 'Shopify
--   returned no row', which is not the same claim as 'Shopify returned zero'.
--   A 0 in this file is a 0 that Shopify actually returned.
--
-- NEGATIVE total_sales IS EXPECTED
--   total_sales is net of refunds and is reported against the day the original
--   order was placed. On a refund-dominated day it can be negative, and a row
--   can carry 0 orders alongside a negative total_sales (e.g. 2023-07-10,
--   2024-02-15, 2025-05-09, 2025-10-12, 2026-03-28). These are real values and
--   must not be clamped to zero.
--
-- ATTRIBUTION CAVEAT - READ BEFORE USING THE 'social' ROW
--   Shopify's referrer_source is LAST-NON-DIRECT attribution: it records the
--   referrer of the session that converted, not every touch that contributed.
--   A customer who sees a post, comes back later by typing the URL, and buys is
--   booked as 'direct'. Because of that, and because in-app browsers and link
--   shorteners routinely strip the referrer, the 'social' row is a FLOOR on
--   social's contribution, not a measurement of it. Do not read a small 'social'
--   number as evidence that social did not drive the sale. The same caveat
--   applies, more weakly, to 'search'.
--
-- CURRENCY  AED. total_sales is a money value, stored unrounded as returned.

CREATE TABLE IF NOT EXISTS shopify_referrer_daily (
  day             date            NOT NULL,
  referrer_source text            NOT NULL,
  sessions        integer,
  orders          integer,
  total_sales     numeric(14,2),
  captured_at     timestamptz     NOT NULL DEFAULT now(),
  PRIMARY KEY (day, referrer_source)
);


